#!/usr/bin/env python3
"""Build README.md and categories/*.md from data/. Edit the data, not the generated pages.

Usage: python3 scripts/build_readme.py [--check]
--check exits 1 if a generated page is out of date (used by CI).
"""
import csv
import json
import os
import re
import sys
import urllib.parse

REPO = "vitalikgpt/gram-ecosystem"
CHANNELS_SHOWN = 20
TOP_REACH = 12
PROBLEMS = "reports/link-check.md"
SOURCES = {
    "gramnews-apps": "the [Gram News apps library](https://gramnews.org/apps)",
    "ton.app": "the [ton.app](https://ton.app) catalogue, full sitemap",
    "dyor.io": "the [DYOR](https://dyor.io) catalogue",
    "findmini": "the [FindMini](https://www.findmini.app) catalogue, TON-related mini apps only",
    "defillama": "[DefiLlama](https://defillama.com/chain/ton), protocols with TVL on TON",
    "tonapi-whitelist": "the [tonapi](https://tonapi.io) token whitelist, from a $100K market cap or 1,000 holders",
    "ton-channel-posts": "bots and product channels linked by at least three different TON channels "
    "(`metric` says how many)",
    "gramnews-feed": "a post on [@gramnews](https://t.me/gramnews)",
    "gramnews-q3-2026": "the [Gram News quarterly map](reports/2026-q3)",
    "ton-society-ecosystem-map": "[ton-society/ecosystem-map](https://github.com/ton-society/ecosystem-map)",
    "awesome-ton": "[ton-community/awesome-ton](https://github.com/ton-community/awesome-ton)",
}
GENERATED = "<!-- Generated by scripts/build_readme.py from data/. Do not edit by hand. -->"


def fmt(n):
    n = int(float(n)) if n not in ("", None) else 0
    if n >= 1_000_000:
        return f"{n / 1e6:.1f}M".replace(".0M", "M")
    if n >= 1_000:
        return f"{n / 1e3:.0f}K"
    return str(n) if n else ""


def cell(s):
    return (s or "").replace("|", "/").replace("[", "(").replace("]", ")")


def short(s, n=90):
    s = cell(s)
    return s if len(s) <= n else s[: n - 1].rsplit(" ", 1)[0] + "…"


def badge(label, value, color="5aa9ff"):
    q = lambda t: urllib.parse.quote(str(t).replace("-", "--").replace("_", "__"))
    return f"https://img.shields.io/badge/{q(label)}-{q(value)}-{color}?style=flat-square"


def links(r):
    out = []
    for key, label in (("telegram", "Telegram"), ("bot", "Bot"), ("x", "X"), ("website", "Site"), ("github", "GitHub"),
                       ("gramnews", "Gram News")):
        if r.get(key):
            out.append(f"[{label}]({r[key]})")
    return " ".join(out)


def activity(r):
    if r["metric"]:
        return r["metric"]
    parts = []
    if r["views_q3"]:
        parts.append(f"{fmt(r['views_q3'])} views")
    if r["mau"] and r["status"] == "active":
        parts.append(f"{fmt(r['mau'])} MAU")
    if not parts and r["last_commit"] >= "2026-07-01" and r["category"] in ("devtools", "infra", "tools"):
        parts.append(f"commit {r['last_commit']}")
    return ", ".join(parts)


def last_seen(r):
    return max(r["last_post"], r["last_commit"]) or ""


def seen_in(r, prefix=""):
    out = []
    for s in r["sources"].split():
        if os.path.exists(f"archive/{s}.jpg"):
            parts = s.split("-")
            year = parts[0] if parts[0].isdigit() else ""
            author = "-".join(p for p in parts if not p.isdigit() and p != "thumb")
            out.append(f"[{author} {year[2:]}]({prefix}archive/{s}.jpg)".replace(" ]", "]"))
    return " ".join(out)


def table(items, prefix=""):
    out = ["| # | Project | What it is | Links | Activity | Last seen | On maps |",
           "| ---: | --- | --- | --- | --- | --- | --- |"]
    for r in items:
        name = f"**{cell(r['name'])}**" + (" ✓" if r["native"] == "1" else "")
        out.append(f"| {r['rank']} | {name} | {short(r['description'])} | {links(r)} | {activity(r)} | {last_seen(r)} | {seen_in(r, prefix)} |")
    return out


def reach_n(r):
    try:
        return int(float(r["reach_q3"] or 0)) or int(float(r["mau"] or 0))
    except ValueError:
        return 0


def build():
    cats = json.load(open("data/categories.json", encoding="utf-8"))
    rows = list(csv.DictReader(open("data/projects.csv", encoding="utf-8")))
    chans = list(csv.DictReader(open("data/channels.csv", encoding="utf-8")))
    unresolved = list(csv.DictReader(open("data/unresolved.csv", encoding="utf-8")))
    by = {}
    for r in rows:
        by.setdefault(r["category"], []).append(r)
    for v in by.values():
        v.sort(key=lambda r: int(r["rank"]))
    count = lambda st, items=rows: sum(1 for r in items if r["status"] == st)
    label = {c["key"]: c["label"] for c in cats}
    try:
        problems = sum(1 for l in open(PROBLEMS, encoding="utf-8") if l.startswith("| ") and not l.startswith("| Project") and not l.startswith("| ---"))
    except FileNotFoundError:
        problems = 0
    try:
        fixes = list(csv.DictReader(open("data/link-fixes.csv", encoding="utf-8")))
    except FileNotFoundError:
        fixes = []
    fixed = sum(1 for f in fixes if f["action"] != "confirm")
    maps = sorted(f[:-4] for f in os.listdir("archive") if f.endswith(".jpg"))
    links_total = sum(1 for r in rows for k in ("telegram", "bot", "x", "website", "github") if r[k])

    pages = {}
    badges = [
        ("projects", f"{len(rows):,}", "5aa9ff"), ("active", f"{count('active'):,}", "4cd08a"),
        ("categories", len(cats), "5aa9ff"), ("links fixed", f"{fixed:,}", "f2b84b"),
        ("data", "CC BY 4.0", "lightgrey"),
    ]
    out = [
        GENERATED,
        "",
        '<img src="assets/cover.jpg" alt="Gram Ecosystem: TON and Telegram projects" width="100%">',
        "",
        "# Gram Ecosystem",
        "",
        " ".join(f'<img src="{badge(a, b, c)}" alt="{a}: {b}">' for a, b, c in badges)
        + f' <a href="https://github.com/{REPO}/actions/workflows/check.yml"><img src="https://github.com/{REPO}/actions/workflows/check.yml/badge.svg" alt="data check"></a>',
        "",
        f"**Every TON and Telegram project we could verify: {len(rows):,} of them in {len(cats)} categories, "
        "each with its channel, bot, X, site and GitHub, and the numbers that show whether it is alive.** "
        f"The {links_total:,} links are checked every week; {fixed:,} wrong ones have been fixed so far, each with its evidence.",
        "",
        "Maintained by [Gram News](https://gramnews.org). Open data: take it, fix it, build on it.",
        "",
        "**Jump to** [Categories](#categories), [Largest projects](#largest-projects), [How to read it](#how-to-read-it), "
        "[Data](#data), [Maps and reports](#maps-and-reports), [Contribute](#contribute)",
        "",
        "## Categories",
        "",
        "Each category has its own page with every project, active ones first.",
        "",
        "| Category | Active | All | Notable projects |",
        "| --- | ---: | ---: | --- |",
    ]
    for c in cats:
        items = by.get(c["key"], [])
        act = [r for r in items if r["status"] == "active"]
        out.append(f"| [{c['label']}](categories/{c['key']}.md) | {len(act)} | {len(items)} | {', '.join(cell(r['name']) for r in act[:4])} |")
    top = sorted((r for r in rows if r["status"] == "active" and r["category"] not in ("tokens", "nftcaps")),
                 key=reach_n, reverse=True)[:TOP_REACH]
    out += [
        "",
        "## Largest projects",
        "",
        "By reach: post views on the project's own channel from July to September 2026, or its bot's monthly users, "
        "whichever is larger.",
        "",
        "| Project | Category | What it is | Reach |",
        "| --- | --- | --- | ---: |",
    ]
    for r in top:
        url = r["telegram"] or r["bot"] or r["website"] or r["x"]
        out.append(f"| [{cell(r['name'])}]({url}) | {label[r['category']]} | {short(r['description'], 70)} | {fmt(reach_n(r))} |")
    out += [
        "",
        "## How to read it",
        "",
        "- **Status** is measured, not judged: `active`, `quiet` or `closed`.",
        "- **Last seen** is the latest post on the project's own channel, or its latest commit.",
        "- **✓** marks projects built for TON, as opposed to global brands and multi-chain services.",
        "- **On maps** links to the ecosystem maps the project appeared on since 2022.",
        "",
        "<details><summary><b>What makes a project active</b></summary>",
        "",
        "At least one of these held from July 1 to September 30, 2026:",
        "",
        "1. its own Telegram channel published a post;",
        "2. its bot showed 1,000+ monthly users on its t.me page;",
        "3. Gram News wrote about it;",
        "4. it had $10,000+ of TVL on TON on DefiLlama;",
        "5. for developer tools and infrastructure, its GitHub repository received a commit.",
        "",
        "Otherwise it is `quiet`, with its links kept. `closed` means the source catalogue marked it as shut down, "
        "or every link it had is dead: the username is free on t.me, the domain no longer resolves, the repository is gone.",
        "",
        "A channel or bot counts for a project only if it matches the project by name: catalogues often carry someone else's.",
        "",
        "</details>",
        "",
        "<details><summary><b>Where the projects come from</b></summary>",
        "",
        "The `sources` column lists every place a project was found:",
        "",
    ]
    for k, v in SOURCES.items():
        out.append(f"- `{k}`: {v};")
    out += [
        "- a date and an author, such as `2024-06-dwf-ventures`: an ecosystem map in the [archive](archive).",
        "",
        "</details>",
        "",
        "## Data",
        "",
        "| File | What is in it |",
        "| --- | --- |",
        f"| [data/projects.csv](data/projects.csv) | {len(rows):,} projects, one per row |",
        f"| [data/channels.csv](data/channels.csv) | {len(chans):,} channels about TON that are not a project's own, with posts and views |",
        "| [data/categories.json](data/categories.json) | categories in display order |",
        f"| [data/link-fixes.csv](data/link-fixes.csv) | {len(fixes):,} link decisions (replaced, removed, confirmed) with evidence |",
        f"| [data/unresolved.csv](data/unresolved.csv) | {len(unresolved)} names from old maps not tied to a project yet |",
        f"| [{PROBLEMS}]({PROBLEMS}) | {problems:,} links that failed the last check |",
        "",
        "<details><summary><b>Columns of projects.csv</b></summary>",
        "",
        "`category`, `rank`, `name`, `slug`, `status`, `on_map`, `native`, `evidence`, `telegram`, `bot`, `x`, `website`, "
        "`github`, `gramnews` (the project's card on gramnews.org), `last_post`, `last_commit`, `launched`, `subscribers`, "
        "`reach_q3`, `views_q3`, `posts_q3`, `mau`, `metric`, `sources`, `description`.",
        "",
        "</details>",
        "",
        "## Maps and reports",
        "",
        "- [**Gram News map, Q3 2026**](reports/2026-q3): the quarterly poster in English and Russian, with the methodology, "
        "and the [article with leaderboards](https://gramnews.org/articles/ton-ecosystem-map-q3-2026).",
        f"- [**Archive of {len(maps)} ecosystem maps**](archive) by Messari, DWF, Coin98, Tonstarter, TON CIS Hub and others, 2022 to 2026.",
        "",
        "## Channels",
        "",
        f"Top {CHANNELS_SHOWN} channels about TON by post views from July to September 2026; all {len(chans):,} in "
        "[data/channels.csv](data/channels.csv).",
        "",
        "| # | Channel | Subscribers | Views |",
        "| ---: | --- | ---: | ---: |",
    ]
    for c in chans[:CHANNELS_SHOWN]:
        out.append(f"| {c['rank']} | [{cell(c['name'])}]({c['telegram']}) | {fmt(c['subscribers'])} | {fmt(c['views_q3'])} |")
    out += [
        "",
        "## Contribute",
        "",
        f"1. **Fix a link.** Start with [{PROBLEMS}]({PROBLEMS}), correct `data/projects.csv` and log the change in "
        "`data/link-fixes.csv` with the page that proves it.",
        f"2. **Tie a name from an old map.** [data/unresolved.csv](data/unresolved.csv) has {len(unresolved)} of them, "
        "half with a candidate channel to check.",
        "3. **Add a project** with at least one link and where you found it.",
        "",
        "Then run `python3 scripts/build_readme.py`; CI checks the rest. Details in [CONTRIBUTING.md](CONTRIBUTING.md).",
        "",
        "## License",
        "",
        "Data (`data/`, `reports/`) under [CC BY 4.0](LICENSE-DATA): reuse freely, credit Gram News. "
        "Scripts under [MIT](LICENSE). Images in `archive/` belong to their authors.",
        "",
        "Not investment advice. A listing only says a project was found and what it did; check it yourself before you use it.",
        "",
    ]
    pages["README.md"] = "\n".join(out)

    for c in cats:
        items = by.get(c["key"], [])
        act = [r for r in items if r["status"] == "active"]
        p = [
            GENERATED,
            "",
            f"# {c['label']}",
            "",
            f"**{len(items)} projects: {len(act)} active, {count('quiet', items)} quiet, {count('closed', items)} closed.** "
            "Back to [all categories](../README.md#categories); statuses are explained [here](../README.md#how-to-read-it).",
            "",
        ]
        if act:
            p += ["## Active", ""] + table(act, "../") + [""]
        for st, title in (("quiet", "Quiet"), ("closed", "Closed")):
            part = [r for r in items if r["status"] == st]
            if part:
                p += [f"<details><summary><b>{title}: {len(part)}</b></summary>", ""] + table(part, "../") + ["", "</details>", ""]
        pages[f"categories/{c['key']}.md"] = "\n".join(p)
    return pages, len(rows), len(cats)


def main():
    pages, n, nc = build()
    if "--check" in sys.argv:
        stale = [p for p, t in pages.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run python3 scripts/build_readme.py")
            sys.exit(1)
        return
    os.makedirs("categories", exist_ok=True)
    for f in os.listdir("categories"):
        if f"categories/{f}" not in pages:
            os.remove(f"categories/{f}")
    for p, t in pages.items():
        open(p, "w", encoding="utf-8").write(t)
    print(f"README.md and {len(pages) - 1} category pages: {n} projects, {nc} categories")


if __name__ == "__main__":
    main()
