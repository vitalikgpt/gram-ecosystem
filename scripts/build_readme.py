def datapackage():
    """Frictionless Data descriptor: what each file is and what each column holds, so tools can load the set as typed tables."""
    res = []
    for name, about in ABOUT.items():
        path = f"data/{name}.csv"
        if not os.path.exists(path):
            continue
        cols = next(csv.reader(open(path, encoding="utf-8")))
        res.append({"name": name, "path": path, "format": "csv", "mediatype": "text/csv", "encoding": "utf-8", "description": about,
                    "schema": {"fields": [{"name": c, "type": "integer" if c in INTS else "string" if c not in DATES else "string",
                                           **({"description": "YYYY-MM-DD"} if c in DATES else {})} for c in cols]}})
    return json.dumps({
        "name": "gram-ecosystem",
        "title": "Gram Ecosystem: TON and Telegram projects",
        "homepage": f"https://github.com/{REPO}",
        "licenses": [{"name": "CC-BY-4.0", "path": "https://creativecommons.org/licenses/by/4.0/", "title": "Creative Commons Attribution 4.0"}],
        "contributors": [{"title": "Gram News", "path": "https://gramnews.org", "role": "author"}],
        "resources": res,
    }, indent=1, ensure_ascii=False) + "\n"


