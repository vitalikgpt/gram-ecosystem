def fmt(n):
    n = int(float(n)) if n not in ("", None) else 0
    if n >= 1_000_000:
        return f"{n / 1e6:.1f}M".replace(".0M", "M")
    if n >= 1_000:
        return f"{n / 1e3:.0f}K"
    return str(n) if n else ""


def cell(s):
    return (s or "").replace("|", "/").replace("[", "(").replace("]", ")")


def short(s):
    """The description as written; no cutting to fit (a sentence with its end lopped off says less than none)."""
    return cell(s)


def home(r):
    """Where a project lives: its channel, else its bot, its site (if it answers) or its X."""
    return r["telegram"] or r["bot"] or (r["website"] if not r.get("website_down") else "") or r["x"]


def icon(r, prefix=""):
    """A 20px copy of the project's Telegram avatar, kept in the repository (assets/icons), never hotlinked."""
    key = r.get("slug") or ("ch-" + r["telegram"].rstrip("/").rsplit("/", 1)[-1].lower() if r.get("telegram") else "")
    if key and os.path.exists(f"assets/icons/{key}.webp"):
        return f'<img src="{prefix}assets/icons/{key}.webp" width="20" height="20" alt=""> '
    return ""


def plink(r, prefix=""):
    url = home(r)
    return icon(r, prefix) + (f"[{cell(r['name'])}]({url})" if url else cell(r["name"]))


EMOJI = re.compile("[\U0001F000-\U0001FAFF\u2600-\u27BF\u2B00-\u2BFF\uFE0F\u200d]")


def tname(s):
    """A channel title as a name: no emoji, no «Name / slogan / slogan» tail."""
    s = EMOJI.sub("", s or "")
    s = re.split(r"\s+(?:/|\||•|—|-)\s+", s)[0]
    return cell(re.sub(r"\s+", " ", s).strip(" -|•/"))


def badge(label, value, color="5aa9ff"):
    q = lambda t: urllib.parse.quote(str(t).replace("-", "--").replace("_", "__"))
    return f"https://img.shields.io/badge/{q(label)}-{q(value)}-{color}?style=flat-square"


def verified(r):
    """«since 2023-10» when the Web Archive dates the badge, «yes» when it is there but undated."""
    if r.get("verified") != "1":
        return ""
    return f"since {r['verified_since'][:7]}" if r.get("verified_since") else "yes"


def links(r):
    out = []
    for key, label in (("telegram", "Telegram"), ("bot", "Bot"), ("x", "X"), ("website", "Site"), ("github", "GitHub"),
                       ("gramnews", "Gram News")):
        if key == "website" and r.get("website_down"):
            out.append("Site (down)")   # the address stays in the data; a dead domain is often resold, so no link
        elif r.get(key):
            out.append(f"[{label}]({r[key]})")
    return " ".join(out)








